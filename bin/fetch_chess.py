#!/usr/bin/env python3
"""Write _data/chess.yml from chess.com's public read API.

No key, no auth: https://api.chess.com/pub/player/<user>/stats. Runs at build
time (see .github/workflows/deploy.yml) alongside bin/fetch_goodreads.py, so
the deployed numbers are as fresh as the last build; the committed
_data/chess.yml is a fallback for local builds and for days the API is down.

Usage: python3 bin/fetch_chess.py [username]
       python3 bin/fetch_chess.py --from-file stats.json   # offline test
"""

import json
import sys
import urllib.error
import urllib.request
from datetime import datetime
from pathlib import Path

USER = "atropos7"
API = "https://api.chess.com/pub/player/{user}/stats"
# chess.com asks that automated callers identify themselves.
UA = "weston-miller.github.io build (w3miller@ucsd.edu)"
OUT = Path(__file__).resolve().parent.parent / "_data" / "chess.yml"
TIMEOUT = 20
MODES = ("rapid", "blitz", "bullet", "daily")


def record_block(name, wins, losses, draws):
    games = wins + losses + draws
    return [
        "{}:".format(name),
        "  wins: {}".format(wins),
        "  losses: {}".format(losses),
        "  draws: {}".format(draws),
        "  games: {}".format(games),
        # Preformatted because Liquid has no thousands-separator filter.
        '  games_pretty: "{:,}"'.format(games),
    ]


def main():
    args = sys.argv[1:]
    if args[:1] == ["--from-file"]:
        source = args[1]
        raw = Path(source).read_text(encoding="utf-8")
    else:
        user = args[0] if args else USER
        source = API.format(user=user)
        request = urllib.request.Request(source, headers={"User-Agent": UA})
        with urllib.request.urlopen(request, timeout=TIMEOUT) as response:
            raw = response.read().decode("utf-8")

    stats = json.loads(raw)

    lines = [
        "# Generated by bin/fetch_chess.py — do not edit by hand.",
        "# Source: " + source,
        "# Last written: " + datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC"),
        "ratings:",
    ]
    for mode in MODES:
        block = stats.get("chess_" + mode) or {}
        rating = (block.get("last") or {}).get("rating")
        if isinstance(rating, int):
            lines.append("  {}: {}".format(mode, rating))

    if len(lines) == 4:  # nothing but the "ratings:" header
        raise ValueError("no ratings found in payload")

    lines.append("peaks:")
    for mode in MODES:
        best = (stats.get("chess_" + mode) or {}).get("best") or {}
        rating, when = best.get("rating"), best.get("date")
        if not isinstance(rating, int):
            continue
        lines.append("  {}:".format(mode))
        lines.append("    rating: {}".format(rating))
        if isinstance(when, int):
            stamp = datetime.utcfromtimestamp(when)
            lines.append('    date: "{}"'.format(stamp.strftime("%Y-%m-%d")))
            lines.append('    month: "{}"'.format(stamp.strftime("%B %Y")))

    # Per-mode records, and their sum: the landing page quotes the total, so it
    # has to be accumulated here rather than added up in Liquid.
    total = {"wins": 0, "losses": 0, "draws": 0}
    for mode in MODES:
        record = (stats.get("chess_" + mode) or {}).get("record") or {}
        wins, losses, draws = (record.get("win"), record.get("loss"), record.get("draw"))
        if not all(isinstance(v, int) for v in (wins, losses, draws)):
            continue
        total["wins"] += wins
        total["losses"] += losses
        total["draws"] += draws
        lines += record_block(mode + "_record", wins, losses, draws)

    if not any(total.values()):
        raise ValueError("no game records found in payload")
    lines += record_block("total_record", total["wins"], total["losses"], total["draws"])

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote {}".format(OUT))


if __name__ == "__main__":
    try:
        main()
    except (urllib.error.URLError, ValueError, KeyError, TimeoutError) as error:
        print("chess.com fetch failed, keeping existing _data/chess.yml: {}".format(error))
        sys.exit(0)
