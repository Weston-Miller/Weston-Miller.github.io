#!/usr/bin/env python3
"""Write _data/reading.yml from a public Goodreads shelf RSS feed.

Goodreads retired its API in 2020, but the per-shelf RSS feeds are still
public. This runs at build time (see .github/workflows/deploy.yml), so the
deployed site is as fresh as its last build; the committed _data/reading.yml
is only a fallback for local builds and for days when Goodreads is down.

Usage: python3 bin/fetch_goodreads.py [user_id] [shelf]
       python3 bin/fetch_goodreads.py --from-file feed.xml   # offline test
"""

import re
import sys
import urllib.error
import urllib.request
import xml.etree.ElementTree as ET
from datetime import datetime
from email.utils import parsedate_to_datetime
from pathlib import Path

USER_ID = "109451240"
SHELF = "currently-reading"
FEED = "https://www.goodreads.com/review/list_rss/{user}?shelf={shelf}"
OUT = Path(__file__).resolve().parent.parent / "_data" / "reading.yml"
TIMEOUT = 20

# "Borne (Borne, #1)" -> "Borne"; leaves other parentheticals alone.
SERIES_SUFFIX = re.compile(r"\s*\([^()]*#[\d.]+\)\s*$")


def quote(value):
    """Minimal YAML double-quoted scalar."""
    return '"' + str(value).replace("\\", "\\\\").replace('"', '\\"') + '"'


def text(item, tag):
    node = item.find(tag)
    return (node.text or "").strip() if node is not None else ""


def main():
    args = sys.argv[1:]
    if args[:1] == ["--from-file"]:
        url = args[1]
        raw = Path(url).read_bytes()
    else:
        user = args[0] if len(args) > 0 else USER_ID
        shelf = args[1] if len(args) > 1 else SHELF
        url = FEED.format(user=user, shelf=shelf)
        request = urllib.request.Request(
            url, headers={"User-Agent": "weston-miller.github.io build"}
        )
        with urllib.request.urlopen(request, timeout=TIMEOUT) as response:
            raw = response.read()

    root = ET.fromstring(raw)
    books = []
    for item in root.iter("item"):
        title = SERIES_SUFFIX.sub("", text(item, "title"))
        if not title:
            continue
        added = text(item, "user_date_added")
        try:
            since = parsedate_to_datetime(added).strftime("%B %Y")
        except (TypeError, ValueError):
            since = ""
        books.append(
            {
                "title": title,
                "author": text(item, "author_name"),
                "link": "https://www.goodreads.com/book/show/" + text(item, "book_id"),
                "since": since,
            }
        )

    lines = [
        "# Generated by bin/fetch_goodreads.py — do not edit by hand.",
        "# Source: " + url,
        "# Last written: " + datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC"),
        "books:",
    ]
    for book in books:
        lines.append("  - title: " + quote(book["title"]))
        lines.append("    author: " + quote(book["author"]))
        lines.append("    link: " + quote(book["link"]))
        lines.append("    since: " + quote(book["since"]))
    if not books:
        lines[-1] = "books: []"

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote {} ({} book{})".format(OUT, len(books), "" if len(books) == 1 else "s"))


if __name__ == "__main__":
    try:
        main()
    except (urllib.error.URLError, ET.ParseError, TimeoutError) as error:
        # Never fail a deploy over this; the committed fallback stands.
        print("goodreads fetch failed, keeping existing _data/reading.yml: {}".format(error))
        sys.exit(0)
